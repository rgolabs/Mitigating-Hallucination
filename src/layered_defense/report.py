"""Render experiment results as LaTeX tables or Markdown."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

# Table 5 of "A Layered Defense Framework for Mitigating Hallucinations in
# Large Language Models" (Govindarajan, June 2026), transcribed from the PDF.
ORIGINAL_TABLE5: dict[int, dict[str, float]] = {
    0: {"hr": 38.4, "lat": 1.1, "cost": 2.0, "help": 3.5},
    1: {"hr": 27.4, "lat": 1.2, "cost": 2.1, "help": 3.7},
    2: {"hr": 18.5, "lat": 1.6, "cost": 3.4, "help": 4.1},
    3: {"hr": 9.3, "lat": 1.6, "cost": 3.4, "help": 4.2},
    4: {"hr": 6.1, "lat": 3.9, "cost": 17.2, "help": 4.3},
}


def _fmt(v: Any, suffix: str = "", nd: int = 1) -> str:
    if v is None:
        return "--"
    if isinstance(v, float):
        return f"{v:.{nd}f}{suffix}"
    return f"{v}{suffix}"


def _tex(s: str) -> str:
    return s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#")


def load_results(path: str | Path) -> dict[str, Any]:
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    if "summary" not in data or "raw_runs" not in data:
        raise ValueError(f"{path} is not a layered-defense results file")
    return data


def is_mock(results: dict[str, Any]) -> bool:
    return results.get("provenance", {}).get("provider") == "mock"


def observations(results: dict[str, Any]) -> list[str]:
    """Data-driven statements about the run; never asserts a trend the numbers do not show."""
    summ = [s for s in results["summary"] if s["n"]]
    prov = results.get("provenance", {})
    out: list[str] = []
    if not summ:
        return ["No configuration produced a usable measurement."]
    n = max(s["n"] for s in summ)
    out.append(
        f"Sample size: {n} question(s) per configuration across {len(prov.get('domains', []))} domain(s); "
        f"95\\% Wilson intervals on the hallucination rate are therefore wide (about $\\pm${100 * 1.96 * (0.25 / n) ** 0.5:.0f} points at HR=50\\%)."
    )
    hrs = [s["hr_pct"] for s in summ]
    first, last = summ[0], summ[-1]
    if all(b <= a for a, b in zip(hrs, hrs[1:], strict=False)):
        trend = "decreases monotonically"
    elif last["hr_pct"] < first["hr_pct"]:
        trend = "decreases overall but not monotonically"
    elif last["hr_pct"] == first["hr_pct"]:
        trend = "does not change"
    else:
        trend = "increases"
    out.append(
        f"The hallucination rate {trend} from {_fmt(first['hr_pct'])}\\% (row {first['row']}) to {_fmt(last['hr_pct'])}\\% (row {last['row']})."
    )
    overlap = all(s["hr_ci95_pct"][0] <= last["hr_ci95_pct"][1] and last["hr_ci95_pct"][0] <= s["hr_ci95_pct"][1] for s in summ)
    if overlap:
        out.append("All per-row confidence intervals overlap, so this run cannot distinguish the configurations statistically.")
    high_refusal = [s for s in summ if (s.get("refusal_pct") or 0) >= 50]
    if high_refusal:
        rows = ", ".join(str(s["row"]) for s in high_refusal)
        out.append(f"Row(s) {rows} refused at least half of the questions; low hallucination there reflects abstention, not accuracy.")
    poisoned = [s for s in summ if s.get("poisoned_context_pct")]
    if poisoned:
        out.append(
            "Adversarial documents reached the prompt in: "
            + "; ".join(f"row {s['row']} ({_fmt(s['poisoned_context_pct'])}\\%)" for s in poisoned)
            + "."
        )
    verifier = [s for s in summ if s.get("corrected_pct") is not None and any(c["verifier"] for c in prov.get("configs", []) if c["row"] == s["row"])]
    for s in verifier:
        out.append(f"The verifier rewrote {_fmt(s['corrected_pct'])}\\% of drafts in row {s['row']}.")
    if any(s["errors"] for s in summ):
        out.append("Some provider calls failed and were excluded: " + ", ".join(f"row {s['row']}: {s['errors']}" for s in summ if s["errors"]) + ".")
    return out


def render_latex(results: dict[str, Any], *, allow_mock: bool = False, original: dict[int, dict[str, float]] = ORIGINAL_TABLE5) -> str:
    if is_mock(results) and not allow_mock:
        raise ValueError("results come from the mock provider; pass allow_mock=True to render them (they are not measurements)")
    prov = results.get("provenance", {})
    models = prov.get("models", {})
    header = (
        "% Auto-generated by `layered-defense report`; do not edit by hand.\n"
        f"% provider={prov.get('provider')} generator={models.get('generator')} verifier={models.get('verifier')} judge={models.get('judge')}\n"
        f"% n_questions={prov.get('n_questions')} seed={prov.get('seed')} started={prov.get('started_at')}\n"
    )
    rows = ""
    for s in results["summary"]:
        ci = f"[{_fmt(s['hr_ci95_pct'][0])}, {_fmt(s['hr_ci95_pct'][1])}]" if s.get("hr_ci95_pct") else "--"
        rows += (
            f"{s['row']} & {_tex(s['configuration'])} & {s['n']} & {_fmt(s['hr_pct'])} & {ci} & {_fmt(s['refusal_pct'])} & "
            f"{_fmt(s['latency_s'], nd=2)} & {_fmt(s['cost_per_1k'], nd=2)} & {_fmt(s['helpful'], nd=2)} \\\\\n"
        )
    replicated = (
        "\\begin{table}[ht]\n\\centering\n\\caption{Replication: cumulative effect of stacking the four security layers "
        f"(generator: \\texttt{{{_tex(str(models.get('generator', '?')))}}}, judge: \\texttt{{{_tex(str(models.get('judge', '?')))}}}).}}\n"
        "\\label{tab:replicated_results}\n\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}{clccccccc}\n\\hline\n"
        "\\textbf{Row} & \\textbf{Configuration} & $n$ & \\textbf{HR (\\%)} & \\textbf{95\\% CI} & \\textbf{Refusal (\\%)} & "
        "\\textbf{Latency (s)} & \\textbf{Cost (\\$/1k)} & \\textbf{Helpful (1--5)} \\\\ \\hline\n" + rows + "\\hline\n\\end{tabular}}\n\\end{table}\n"
    )
    comp_rows = ""
    for s in results["summary"]:
        o = original.get(s["row"])
        if not o:
            continue
        comp_rows += (
            f"{s['row']} & {_fmt(o['hr'])} & {_fmt(s['hr_pct'])} & {_fmt(o['lat'])} & {_fmt(s['latency_s'], nd=2)} & "
            f"{_fmt(o['cost'])} & {_fmt(s['cost_per_1k'], nd=2)} & {_fmt(o['help'])} & {_fmt(s['helpful'], nd=2)} \\\\\n"
        )
    comparison = (
        "\\begin{table}[ht]\n\\centering\n\\caption{Original (Table 5 of the original study) vs. replicated metrics.}\n"
        "\\label{tab:replication_comparison}\n\\small\n\\begin{tabular}{c|cc|cc|cc|cc}\n\\hline\n"
        "\\textbf{Row} & \\multicolumn{2}{c|}{\\textbf{HR (\\%)}} & \\multicolumn{2}{c|}{\\textbf{Latency (s)}} & "
        "\\multicolumn{2}{c|}{\\textbf{Cost (\\$/1k)}} & \\multicolumn{2}{c}{\\textbf{Helpful (1--5)}} \\\\\n"
        " & Orig & Repl & Orig & Repl & Orig & Repl & Orig & Repl \\\\ \\hline\n" + comp_rows + "\\hline\n\\end{tabular}\n\\end{table}\n"
    )
    obs = "\\begin{itemize}\n" + "".join(f"  \\item {o}\n" for o in observations(results)) + "\\end{itemize}\n"
    return header + "\n" + replicated + "\n" + comparison + "\n% Data-driven observations\n" + obs


def render_markdown(results: dict[str, Any]) -> str:
    prov = results.get("provenance", {})
    lines = [
        f"Provider: {prov.get('provider')}  models: {prov.get('models')}  n={prov.get('n_questions')} seed={prov.get('seed')}",
        "",
        "| Row | Configuration | n | HR % | 95% CI | Refusal % | Corrected % | Poisoned ctx % | Latency s | $/1k | Helpful |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for s in results["summary"]:
        ci = f"{s['hr_ci95_pct'][0]}–{s['hr_ci95_pct'][1]}" if s.get("hr_ci95_pct") else "--"
        lines.append(
            f"| {s['row']} | {s['configuration']} | {s['n']}{'+' + str(s['errors']) + ' err' if s['errors'] else ''} | {_fmt(s['hr_pct'])} | {ci} | "
            f"{_fmt(s['refusal_pct'])} | {_fmt(s['corrected_pct'])} | {_fmt(s['poisoned_context_pct'])} | {_fmt(s['latency_s'], nd=2)} | "
            f"{_fmt(s['cost_per_1k'], nd=3)} | {_fmt(s['helpful'], nd=2)} |"
        )
    lines += ["", *[f"- {o.replace(chr(92) + '%', '%').replace('$' + chr(92) + 'pm$', '±')}" for o in observations(results)]]
    if is_mock(results):
        lines.append("\n**Mock provider: these numbers exercise the plumbing only and are not measurements.**")
    return "\n".join(lines) + "\n"
